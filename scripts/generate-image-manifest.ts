// Writes content hashes for public/images/**/*.{png,jpg} and public/documents/**/*.pdf.
// The Angular app imports the TypeScript module; the index.html stamp reads
// the JSON file.
// Usage: bun run images:manifest

import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { contentHashId } from './image-sync-plan';

const ROOTS = [
  { dir: 'public/images', extensions: ['.png', '.jpg'] },
  { dir: 'public/documents', extensions: ['.pdf'] },
] as const;
const OUT_TS = 'src/app/core/images/image-manifest.generated.ts';
const OUT_JSON = 'src/app/core/images/image-manifest.generated.json';

async function collectFiles(
  dir: string,
  extensions: readonly string[]
): Promise<string[]> {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch (error) {
    if (isMissing(error)) {
      return [];
    }
    throw error;
  }

  const files: string[] = [];
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectFiles(path, extensions)));
    } else if (
      entry.isFile() &&
      extensions.some((extension) => entry.name.endsWith(extension))
    ) {
      files.push(path);
    }
  }
  return files;
}

function isMissing(error: unknown): boolean {
  return (
    typeof error === 'object' &&
    error !== null &&
    'code' in error &&
    error.code === 'ENOENT'
  );
}

function logicalKey(file: string): string {
  return relative('public', file).split(sep).join('/');
}

async function hashFile(file: string): Promise<string> {
  const bytes = await readFile(file);
  return contentHashId(createHash('sha256').update(bytes).digest('hex'));
}

function renderModule(manifest: Readonly<Record<string, string>>): string {
  const body = JSON.stringify(manifest, null, 2);
  return `// Generated by scripts/generate-image-manifest.ts. Do not edit.\n\nexport const IMAGE_MANIFEST: Readonly<Record<string, string>> = ${body};\n`;
}

async function main(): Promise<void> {
  const files = (
    await Promise.all(
      ROOTS.map((root) => collectFiles(root.dir, root.extensions))
    )
  ).flat();
  const manifest: Record<string, string> = {};
  for (const file of files) {
    const info = await stat(file);
    if (!info.isFile()) {
      continue;
    }
    manifest[logicalKey(file)] = await hashFile(file);
  }

  const keys = Object.keys(manifest).sort((a, b) => a.localeCompare(b));
  const sorted: Record<string, string> = {};
  for (const key of keys) {
    const hash = manifest[key];
    if (hash !== undefined) {
      sorted[key] = hash;
    }
  }

  await writeFile(OUT_JSON, `${JSON.stringify(sorted, null, 2)}\n`);
  await writeFile(OUT_TS, renderModule(sorted));
  console.log(`Wrote ${keys.length} asset hash(es).`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
